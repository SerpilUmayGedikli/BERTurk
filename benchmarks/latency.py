"""Latency benchmark for the MCP tools, measured end to end through an in-memory MCP client
(tool-call serialization and schema validation included, transport excluded).

    MODEL_PATH=... uv run python benchmarks/latency.py [--device cpu] [--out benchmarks/results.md]

Measures:
- classify_text: mean and p95 per call over N calls
- classify_batch with 1/8/32/64 texts: mean time per call and per text
- explain_prediction: mean and p95 per call

Latency depends only on the architecture (BERT-base) and input lengths, not on the
weights, so a smoke checkpoint gives the same numbers as a fully trained one.
"""

from __future__ import annotations

import argparse
import json
import os
import platform
import statistics
import time
from collections.abc import Awaitable, Callable
from pathlib import Path
from typing import Any

import anyio
import numpy as np
from mcp import Client

from tcls_mcp.config import Settings
from tcls_mcp.server import build_server

ROOT = Path(__file__).resolve().parents[1]
REVIEWS = ROOT / "examples" / "reviews_20.txt"
BATCH_SIZES = (1, 8, 32, 64)


def texts(n: int) -> list[str]:
    base = [line for line in REVIEWS.read_text(encoding="utf-8").splitlines() if line.strip()]
    return [base[i % len(base)] for i in range(n)]


async def timed(fn: Callable[[], Awaitable[Any]], repeats: int, warmup: int) -> list[float]:
    for _ in range(warmup):
        await fn()
    out = []
    for _ in range(repeats):
        t0 = time.perf_counter()
        r = await fn()
        out.append((time.perf_counter() - t0) * 1e3)
        if r.is_error:
            raise RuntimeError(r.content)
    return out


def p95(xs: list[float]) -> float:
    return float(np.percentile(xs, 95))


def cpu_name() -> str:
    try:
        import torch

        if torch.cuda.is_available():
            return str(torch.cuda.get_device_name(0))
    except ImportError:
        pass
    return platform.processor() or platform.machine()


async def run(settings: Settings, single_n: int, batch_repeats: int) -> str:
    import torch

    sample = texts(64)
    rows: list[str] = []
    async with Client(build_server(settings)) as c:
        i = 0

        async def one() -> Any:
            nonlocal i
            i += 1
            return await c.call_tool("classify_text", {"text": sample[i % len(sample)]})

        single = await timed(one, single_n, warmup=5)

        batch_rows = []
        for size in BATCH_SIZES:
            chunk = sample[:size]

            async def batch(chunk: list[str] = chunk) -> Any:
                return await c.call_tool("classify_batch", {"texts": chunk})

            ms = await timed(batch, batch_repeats, warmup=2)
            mean = statistics.mean(ms)
            batch_rows.append((size, mean, p95(ms), mean / size))

        j = 0

        async def expl() -> Any:
            nonlocal j
            j += 1
            return await c.call_tool("explain_prediction", {"text": sample[j % 20]})

        explain_ms = await timed(expl, max(10, single_n // 5), warmup=2)

        card = (await c.read_resource("model://card")).contents[0]
        device = str(json.loads(card.text)["device"])  # type: ignore[union-attr]

    lens = [len(t.split()) for t in sample[:20]]
    rows += [
        "# Latency benchmark",
        "",
        "Generated by `benchmarks/latency.py`. End-to-end MCP tool calls through an in-memory",
        "client (no stdio transport). Inputs: the 20 reviews in `examples/reviews_20.txt`",
        f"({min(lens)}-{max(lens)} words each), cycled.",
        "",
        f"- Hardware: {cpu_name()} ({'GPU' if 'cuda' in device else 'CPU'}), "
        f"torch {torch.__version__}, {torch.get_num_threads()} threads, "
        f"Python {platform.python_version()}, {platform.system()}",
        f"- Model: `{settings.model_path.parent.name}/{settings.model_path.name}` (BERT-base)",
        "",
        "## classify_text",
        "",
        "| calls | mean (ms) | p95 (ms) |",
        "|---:|---:|---:|",
        f"| {single_n} | {statistics.mean(single):.1f} | {p95(single):.1f} |",
        "",
        "## classify_batch",
        "",
        "| batch size | mean per call (ms) | p95 per call (ms) | mean per text (ms) |",
        "|---:|---:|---:|---:|",
        *[f"| {s} | {m:.1f} | {p:.1f} | {t:.1f} |" for s, m, p, t in batch_rows],
        "",
        "## explain_prediction",
        "",
        "| calls | mean (ms) | p95 (ms) |",
        "|---:|---:|---:|",
        f"| {len(explain_ms)} | {statistics.mean(explain_ms):.1f} | {p95(explain_ms):.1f} |",
        "",
    ]
    return "\n".join(rows)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    ap.add_argument("--device", default=os.environ.get("DEVICE", "auto"))
    ap.add_argument("--single", type=int, default=100, help="classify_text calls")
    ap.add_argument("--repeats", type=int, default=10, help="calls per batch size")
    ap.add_argument("--out", type=Path, default=ROOT / "benchmarks" / "results.md")
    args = ap.parse_args()

    env = {**os.environ, "DEVICE": args.device, "LOG_LEVEL": "WARNING"}
    settings = Settings.from_env(env)
    report = anyio.run(run, settings, args.single, args.repeats)
    args.out.write_text(report, encoding="utf-8")
    print(report)


if __name__ == "__main__":
    main()
