"""Aggregate per-seed BERTurk run JSONs (mean ± std) and compare with the baselines.

    python -m tcls.aggregate --configs configs/*.yaml

Reads ``reports/berturk_<task>_<tag>_seed<N>.json`` (smoke runs are ignored) and
``reports/baseline_<task>.json``. Every planned config (one with a ``training`` section) is
listed; configs without runs are marked "NOT RUN (to be run on Colab/Kaggle)".
std is the sample standard deviation (ddof=1) over seeds.
"""

from __future__ import annotations

import argparse
import json
import math
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from tcls.utils import get_logger, load_raw_config

logger = get_logger(__name__)

NOT_RUN = "NOT RUN (to be run on Colab/Kaggle)"
DEFAULT_SEEDS = (42, 43, 44)


def mean_std(values: Sequence[float]) -> tuple[float, float | None]:
    """Mean and sample std (ddof=1); std is None for a single value."""
    if not values:
        raise ValueError("No values")
    m = sum(values) / len(values)
    if len(values) < 2:
        return m, None
    var = sum((v - m) ** 2 for v in values) / (len(values) - 1)
    return m, math.sqrt(var)


def fmt(m: float, s: float | None, scale: float = 100.0) -> str:
    return f"{m * scale:.2f}" if s is None else f"{m * scale:.2f} ± {s * scale:.2f}"


@dataclass(frozen=True)
class Planned:
    task: str
    tag: str
    config: str


def planned_runs(config_paths: Sequence[str | Path]) -> list[Planned]:
    out = []
    for p in config_paths:
        raw = load_raw_config(p)
        if "training" in raw:
            out.append(Planned(str(raw["task"]), str(raw["training"]["tag"]), str(p)))
    return out


def load_runs(report_dir: str | Path) -> list[dict[str, Any]]:
    runs = []
    for path in sorted(Path(report_dir).glob("berturk_*_seed*.json")):
        r = json.loads(path.read_text(encoding="utf-8"))
        if r.get("smoke"):
            continue
        runs.append(r)
    return runs


def summarize_group(runs: Sequence[Mapping[str, Any]]) -> dict[str, Any]:
    """mean/std over seeds for one (task, tag)."""
    seeds = sorted(int(r["seed"]) for r in runs)
    if len(set(seeds)) != len(seeds):
        raise ValueError(f"Duplicate seeds in group: {seeds}")
    out: dict[str, Any] = {"seeds": seeds, "n": len(runs)}
    for split in ("validation", "test"):
        for metric in ("macro_f1", "accuracy"):
            m, s = mean_std([float(r[split][metric]) for r in runs])
            out[f"{split}_{metric}"] = {"mean": m, "std": s}
    labels = list(runs[0]["labels"])
    out["test_per_class_f1"] = {}
    for lab in labels:
        m, s = mean_std([float(r["test"]["per_class"][lab]["f1"]) for r in runs])
        out["test_per_class_f1"][lab] = {"mean": m, "std": s}
    if all("test_focus_label" in r for r in runs):
        focus = runs[0]["test_focus_label"]["label"]
        out["focus_label"] = {"label": focus}
        for k in ("precision", "recall", "f1"):
            m, s = mean_std([float(r["test_focus_label"][k]) for r in runs])
            out["focus_label"][k] = {"mean": m, "std": s}
    out["max_train_samples"] = runs[0]["hyperparameters"].get("max_train_samples")
    out["train_size"] = runs[0]["data"]["used_sizes"]["train"]
    out["gpus"] = sorted({str(r["device"].get("gpu_name")) for r in runs})
    return out


def aggregate(
    runs: Sequence[Mapping[str, Any]],
    planned: Sequence[Planned],
    expected_seeds: Sequence[int] = DEFAULT_SEEDS,
) -> dict[str, dict[str, Any]]:
    """Return {task: {tag: summary | {"status": NOT_RUN}}}."""
    groups: dict[tuple[str, str], list[Mapping[str, Any]]] = {}
    for r in runs:
        groups.setdefault((str(r["task"]), str(r["tag"])), []).append(r)
    out: dict[str, dict[str, Any]] = {}
    keys = [(p.task, p.tag) for p in planned] + [
        k for k in groups if k not in {(p.task, p.tag) for p in planned}
    ]
    for task, tag in keys:
        group = groups.get((task, tag), [])
        if not group:
            out.setdefault(task, {})[tag] = {"status": NOT_RUN}
            continue
        summary = summarize_group(group)
        missing = sorted(set(expected_seeds) - set(summary["seeds"]))
        summary["status"] = "complete" if not missing else f"partial: missing seeds {missing}"
        out.setdefault(task, {})[tag] = summary
    return out


def load_baseline(report_dir: str | Path, task: str) -> dict[str, Any] | None:
    p = Path(report_dir) / f"baseline_{task}.json"
    if not p.exists():
        return None
    data: dict[str, Any] = json.loads(p.read_text(encoding="utf-8"))
    return data


def render_markdown(
    agg: Mapping[str, Mapping[str, Any]], baselines: Mapping[str, Mapping[str, Any] | None]
) -> str:
    lines = [
        "# BERTurk vs. baseline",
        "",
        "Generated by `python -m tcls.aggregate`. BERTurk: mean ± sample std (ddof=1) over seeds;",
        "checkpoint chosen on validation macro-F1, test scored once per run. Baselines: one",
        "deterministic run each (no std). Smoke runs are excluded.",
        "",
    ]
    for task in sorted(set(agg) | {t for t, b in baselines.items() if b}):
        lines += [
            f"## {task}",
            "",
            "| model | runs | train size | val macro-F1 | test macro-F1 | test accuracy |",
            "|---|---|---:|---:|---:|---:|",
        ]
        base = baselines.get(task)
        if base:
            for name, m in base["models"].items():
                lines.append(
                    f"| TF-IDF + {name} | 1 (deterministic) | {base['sizes']['train']} "
                    f"| {fmt(m['validation']['macro_f1'], None)} "
                    f"| {fmt(m['test']['macro_f1'], None)} "
                    f"| {fmt(m['test']['accuracy'], None)} |"
                )
        focus_rows = []
        for tag, s in agg.get(task, {}).items():
            if s["status"] == NOT_RUN:
                lines.append(f"| BERTurk `{tag}` | {NOT_RUN} | | | | |")
                continue
            runs = f"{s['n']} (seeds {', '.join(map(str, s['seeds']))})"
            if s["status"] != "complete":
                runs += f"; {s['status']}"
            lines.append(
                f"| BERTurk `{tag}` | {runs} | {s['train_size']} "
                f"| {fmt(s['validation_macro_f1']['mean'], s['validation_macro_f1']['std'])} "
                f"| {fmt(s['test_macro_f1']['mean'], s['test_macro_f1']['std'])} "
                f"| {fmt(s['test_accuracy']['mean'], s['test_accuracy']['std'])} |"
            )
            if "focus_label" in s:
                f = s["focus_label"]
                focus_rows.append(
                    f"| BERTurk `{tag}` | {fmt(f['precision']['mean'], f['precision']['std'])} "
                    f"| {fmt(f['recall']['mean'], f['recall']['std'])} |"
                )
        if focus_rows:
            label = next(
                s["focus_label"]["label"] for s in agg[task].values() if "focus_label" in s
            )
            lines += [
                "",
                f"Test `{label}` precision / recall:",
                "",
                "| model | precision | recall |",
                "|---|---:|---:|",
            ]
            if base:
                for name, m in base["models"].items():
                    pc = m["test"]["per_class"].get(label)
                    if pc:
                        lines.append(
                            f"| TF-IDF + {name} | {fmt(pc['precision'], None)} "
                            f"| {fmt(pc['recall'], None)} |"
                        )
            lines += focus_rows
        lines.append("")
    return "\n".join(lines)


def main(argv: Sequence[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Aggregate BERTurk runs over seeds.")
    parser.add_argument("--configs", nargs="+", required=True, help="Planned run configs")
    parser.add_argument("--report-dir", default="reports")
    parser.add_argument("--seeds", type=int, nargs="+", default=list(DEFAULT_SEEDS))
    parser.add_argument("--out", default="reports/berturk_summary")
    args = parser.parse_args(argv)

    planned = planned_runs(args.configs)
    agg = aggregate(load_runs(args.report_dir), planned, args.seeds)
    baselines = {task: load_baseline(args.report_dir, task) for task in agg}
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.with_suffix(".json").write_text(
        json.dumps(agg, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    out.with_suffix(".md").write_text(render_markdown(agg, baselines), encoding="utf-8")
    logger.info("Wrote %s.{json,md}", out)


if __name__ == "__main__":
    main()
